from typing import TypedDict, List, Annotated               # Import tools to define data types and structure
import operator                                     # Import built-in operations, such as adding lists

class AgentState(TypedDict):                                   # Define the structure of the agent's shared state

    messages: Annotated[List[dict], operator.add]               #to maintain agent state internally
    current_query: str                                          # Store the user's current question
    documents: List[str]                                     # Store the retrieved document chunks
    plan: List[str]                                         # Store the steps the agent plans to follow
    status: str                                              # Track current status of the agent (on which node it is present)
    final_answer: str                                       # Save the final response generated by the agent